#[derive(Clone, Copy, Debug)]
pub(super) enum MenuItem {
    Action(Command),
    Toggle(Command),
    Planned(&'static str),
    Group(&'static str, &'static [MenuItem]),
    Separator,
}

use MenuItem::{Action, Group, Planned, Separator, Toggle};

pub(super) fn entries(menu: TopMenu) -> &'static [MenuItem] {
    match menu {
        TopMenu::File => FILE,
        TopMenu::Edit => EDIT,
        TopMenu::Layer => LAYER,
        TopMenu::Select => SELECT,
        TopMenu::View => VIEW,
        TopMenu::Filter => FILTER,
        TopMenu::Window => WINDOW,
        TopMenu::Help => HELP,
    }
}

